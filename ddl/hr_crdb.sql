-- CockroachDB schema for the Oracle HR sample.
-- Identifiers are double-quoted so names stay case-sensitive.
-- LOCATION_ID, DEPARTMENT_ID, and EMPLOYEE_ID stay INT8 so MOLT Fetch can
-- load the Oracle values. A stored UUID beside each one is md5 of that
-- integer, so the same number produces the same UUID on parent and child.
-- No sequences are created. Foreign keys are added, then dropped: CockroachDB
-- cannot disable a foreign key in place, and NOT VALID still checks new rows.

CREATE SCHEMA IF NOT EXISTS "HR";

CREATE TABLE "HR"."REGIONS" (
  "REGION_ID" INT8 CONSTRAINT "REGION_ID_NN" NOT NULL,
  "REGION_NAME" VARCHAR(25),
  CONSTRAINT "REG_ID_PK" PRIMARY KEY ("REGION_ID")
);

CREATE TABLE "HR"."COUNTRIES" (
  "COUNTRY_ID" CHAR(2) CONSTRAINT "COUNTRY_ID_NN" NOT NULL,
  "COUNTRY_NAME" VARCHAR(60),
  "REGION_ID" INT8,
  CONSTRAINT "COUNTRY_C_ID_PK" PRIMARY KEY ("COUNTRY_ID")
);

CREATE TABLE "HR"."LOCATIONS" (
  "LOCATION_ID" INT8 NOT NULL,
  "LOCATION_UUID" UUID AS (md5("LOCATION_ID"::STRING)::UUID) STORED,
  "STREET_ADDRESS" VARCHAR(40),
  "POSTAL_CODE" VARCHAR(12),
  "CITY" VARCHAR(30) CONSTRAINT "LOC_CITY_NN" NOT NULL,
  "STATE_PROVINCE" VARCHAR(25),
  "COUNTRY_ID" CHAR(2),
  CONSTRAINT "LOC_ID_PK" PRIMARY KEY ("LOCATION_ID"),
  CONSTRAINT "LOC_UUID_UQ" UNIQUE ("LOCATION_UUID")
);

CREATE TABLE "HR"."JOBS" (
  "JOB_ID" VARCHAR(10) NOT NULL,
  "JOB_TITLE" VARCHAR(35) CONSTRAINT "JOB_TITLE_NN" NOT NULL,
  "MIN_SALARY" INT8,
  "MAX_SALARY" INT8,
  CONSTRAINT "JOB_ID_PK" PRIMARY KEY ("JOB_ID")
);

CREATE TABLE "HR"."DEPARTMENTS" (
  "DEPARTMENT_ID" INT8 NOT NULL,
  "DEPARTMENT_UUID" UUID AS (md5("DEPARTMENT_ID"::STRING)::UUID) STORED,
  "DEPARTMENT_NAME" VARCHAR(30) CONSTRAINT "DEPT_NAME_NN" NOT NULL,
  "MANAGER_ID" INT8,
  "MANAGER_UUID" UUID AS (md5("MANAGER_ID"::STRING)::UUID) STORED,
  "LOCATION_ID" INT8,
  "LOCATION_UUID" UUID AS (md5("LOCATION_ID"::STRING)::UUID) STORED,
  CONSTRAINT "DEPT_ID_PK" PRIMARY KEY ("DEPARTMENT_ID"),
  CONSTRAINT "DEPT_UUID_UQ" UNIQUE ("DEPARTMENT_UUID")
);

CREATE TABLE "HR"."EMPLOYEES" (
  "EMPLOYEE_ID" INT8 NOT NULL,
  "EMPLOYEE_UUID" UUID AS (md5("EMPLOYEE_ID"::STRING)::UUID) STORED,
  "FIRST_NAME" VARCHAR(20),
  "LAST_NAME" VARCHAR(25) CONSTRAINT "EMP_LAST_NAME_NN" NOT NULL,
  "EMAIL" VARCHAR(25) CONSTRAINT "EMP_EMAIL_NN" NOT NULL,
  "PHONE_NUMBER" VARCHAR(20),
  "HIRE_DATE" TIMESTAMP CONSTRAINT "EMP_HIRE_DATE_NN" NOT NULL,
  "JOB_ID" VARCHAR(10) CONSTRAINT "EMP_JOB_NN" NOT NULL,
  "SALARY" DECIMAL(8,2),
  "COMMISSION_PCT" DECIMAL(2,2),
  "MANAGER_ID" INT8,
  "MANAGER_UUID" UUID AS (md5("MANAGER_ID"::STRING)::UUID) STORED,
  "DEPARTMENT_ID" INT8,
  "DEPARTMENT_UUID" UUID AS (md5("DEPARTMENT_ID"::STRING)::UUID) STORED,
  CONSTRAINT "EMP_SALARY_MIN" CHECK ("SALARY" > 0),
  CONSTRAINT "EMP_EMAIL_UK" UNIQUE ("EMAIL"),
  CONSTRAINT "EMP_EMP_ID_PK" PRIMARY KEY ("EMPLOYEE_ID"),
  CONSTRAINT "EMP_UUID_UQ" UNIQUE ("EMPLOYEE_UUID")
);

CREATE TABLE "HR"."JOB_HISTORY" (
  "EMPLOYEE_ID" INT8 CONSTRAINT "JHIST_EMPLOYEE_NN" NOT NULL,
  "EMPLOYEE_UUID" UUID AS (md5("EMPLOYEE_ID"::STRING)::UUID) STORED,
  "START_DATE" TIMESTAMP CONSTRAINT "JHIST_START_DATE_NN" NOT NULL,
  "END_DATE" TIMESTAMP CONSTRAINT "JHIST_END_DATE_NN" NOT NULL,
  "JOB_ID" VARCHAR(10) CONSTRAINT "JHIST_JOB_NN" NOT NULL,
  "DEPARTMENT_ID" INT8,
  "DEPARTMENT_UUID" UUID AS (md5("DEPARTMENT_ID"::STRING)::UUID) STORED,
  CONSTRAINT "JHIST_DATE_INTERVAL" CHECK ("END_DATE" > "START_DATE"),
  CONSTRAINT "JHIST_EMP_ID_ST_DATE_PK" PRIMARY KEY ("EMPLOYEE_ID", "START_DATE")
);

CREATE INDEX "DEPT_LOCATION_IX" ON "HR"."DEPARTMENTS" ("LOCATION_ID");
CREATE INDEX "EMP_DEPARTMENT_IX" ON "HR"."EMPLOYEES" ("DEPARTMENT_ID");
CREATE INDEX "EMP_JOB_IX" ON "HR"."EMPLOYEES" ("JOB_ID");
CREATE INDEX "EMP_MANAGER_IX" ON "HR"."EMPLOYEES" ("MANAGER_ID");
CREATE INDEX "EMP_NAME_IX" ON "HR"."EMPLOYEES" ("LAST_NAME", "FIRST_NAME");
CREATE INDEX "JHIST_DEPARTMENT_IX" ON "HR"."JOB_HISTORY" ("DEPARTMENT_ID");
CREATE INDEX "JHIST_EMPLOYEE_IX" ON "HR"."JOB_HISTORY" ("EMPLOYEE_ID");
CREATE INDEX "JHIST_JOB_IX" ON "HR"."JOB_HISTORY" ("JOB_ID");
CREATE INDEX "LOC_CITY_IX" ON "HR"."LOCATIONS" ("CITY");
CREATE INDEX "LOC_COUNTRY_IX" ON "HR"."LOCATIONS" ("COUNTRY_ID");
CREATE INDEX "LOC_STATE_PROVINCE_IX" ON "HR"."LOCATIONS" ("STATE_PROVINCE");

ALTER TABLE "HR"."COUNTRIES"
  ADD CONSTRAINT "COUNTR_REG_FK"
  FOREIGN KEY ("REGION_ID") REFERENCES "HR"."REGIONS" ("REGION_ID");

ALTER TABLE "HR"."LOCATIONS"
  ADD CONSTRAINT "LOC_C_ID_FK"
  FOREIGN KEY ("COUNTRY_ID") REFERENCES "HR"."COUNTRIES" ("COUNTRY_ID");

ALTER TABLE "HR"."DEPARTMENTS"
  ADD CONSTRAINT "DEPT_LOC_FK"
  FOREIGN KEY ("LOCATION_UUID") REFERENCES "HR"."LOCATIONS" ("LOCATION_UUID");

ALTER TABLE "HR"."EMPLOYEES"
  ADD CONSTRAINT "EMP_DEPT_FK"
  FOREIGN KEY ("DEPARTMENT_UUID") REFERENCES "HR"."DEPARTMENTS" ("DEPARTMENT_UUID");

ALTER TABLE "HR"."EMPLOYEES"
  ADD CONSTRAINT "EMP_JOB_FK"
  FOREIGN KEY ("JOB_ID") REFERENCES "HR"."JOBS" ("JOB_ID");

ALTER TABLE "HR"."EMPLOYEES"
  ADD CONSTRAINT "EMP_MANAGER_FK"
  FOREIGN KEY ("MANAGER_UUID") REFERENCES "HR"."EMPLOYEES" ("EMPLOYEE_UUID");

ALTER TABLE "HR"."DEPARTMENTS"
  ADD CONSTRAINT "DEPT_MGR_FK"
  FOREIGN KEY ("MANAGER_UUID") REFERENCES "HR"."EMPLOYEES" ("EMPLOYEE_UUID");

ALTER TABLE "HR"."JOB_HISTORY"
  ADD CONSTRAINT "JHIST_JOB_FK"
  FOREIGN KEY ("JOB_ID") REFERENCES "HR"."JOBS" ("JOB_ID");

ALTER TABLE "HR"."JOB_HISTORY"
  ADD CONSTRAINT "JHIST_EMP_FK"
  FOREIGN KEY ("EMPLOYEE_UUID") REFERENCES "HR"."EMPLOYEES" ("EMPLOYEE_UUID");

ALTER TABLE "HR"."JOB_HISTORY"
  ADD CONSTRAINT "JHIST_DEPT_FK"
  FOREIGN KEY ("DEPARTMENT_UUID") REFERENCES "HR"."DEPARTMENTS" ("DEPARTMENT_UUID");

